import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { printSchema } from "graphql";
import { diffModels, emptySnapshot, Snapshot, snapshotOf } from "./models/ddl";
import { loadModels, ModelError } from "./models/load";
import { ModelDef } from "./models/types";
import { buildSchema } from "./schema";

/**
 * `npm run generate`: turns the model definitions into
 *   - migrations/NNNN_<change>.sql for the difference from the snapshot of
 *     the last generated migration (migrations/models.snapshot.json)
 *   - generated/schema.graphql, a printout of the GraphQL schema for review
 *
 * Options:
 *   --check     change nothing; fail if a migration or the schema printout
 *               is missing (tests and CI)
 *   --baseline  accept the models as they are (snapshot and printout only, no
 *               migration), after a hand-written migration
 */

const ROOT = resolve(__dirname, "..");
export const MIGRATIONS_DIR = join(ROOT, "migrations");
export const SNAPSHOT_FILE = join(MIGRATIONS_DIR, "models.snapshot.json");
export const SCHEMA_FILE = join(ROOT, "generated", "schema.graphql");

export const readSnapshot = (): Snapshot =>
  existsSync(SNAPSHOT_FILE)
    ? (JSON.parse(readFileSync(SNAPSHOT_FILE, "utf8")) as Snapshot)
    : emptySnapshot();

export const schemaText = (models: readonly ModelDef[]): string =>
  `# Generated by \`npm run generate\` from models/*.yaml. Do not edit.\n\n${printSchema(buildSchema(models))}\n`;

const snapshotText = (models: readonly ModelDef[]): string =>
  `${JSON.stringify(snapshotOf(models), null, 2)}\n`;

const nextMigration = (summary: string[]): string => {
  const numbers = readdirSync(MIGRATIONS_DIR)
    .map((f) => /^(\d{4})_.*\.sql$/.exec(f)?.[1])
    .filter((n): n is string => n !== undefined)
    .map(Number);
  const next = String(Math.max(0, ...numbers) + 1).padStart(4, "0");
  const slug = summary.length === 1 ? summary[0].replace(/[^a-z0-9]+/gi, "_").toLowerCase() : "update_models";
  return join(MIGRATIONS_DIR, `${next}_${slug}.sql`);
};

const main = (args: string[]): number => {
  const check = args.includes("--check");
  const baseline = args.includes("--baseline");
  const models = loadModels();
  const schema = schemaText(models);
  const schemaCurrent = existsSync(SCHEMA_FILE) && readFileSync(SCHEMA_FILE, "utf8") === schema;

  if (baseline) {
    writeFileSync(SNAPSHOT_FILE, snapshotText(models));
    mkdirSync(join(ROOT, "generated"), { recursive: true });
    writeFileSync(SCHEMA_FILE, schema);
    console.log("Snapshot and schema printout updated; no migration written.");
    return 0;
  }

  const changes = diffModels(readSnapshot(), models);
  if (check) {
    const problems = [
      ...changes.summary.map((s) => `missing migration: ${s}`),
      ...(schemaCurrent ? [] : ["generated/schema.graphql is out of date"]),
    ];
    problems.forEach((p) => console.error(p));
    if (problems.length > 0) console.error("Run `npm run generate`.");
    return problems.length > 0 ? 1 : 0;
  }

  if (changes.statements.length > 0) {
    const file = nextMigration(changes.summary);
    writeFileSync(
      file,
      "-- Generated by `npm run generate` from models/*.yaml:\n" +
        changes.summary.map((s) => `--   ${s}\n`).join("") +
        "-- Apply with scripts/migrate.sh, then run scripts/replication-setup.sh\n" +
        "-- (new tables must be replicated before the API writes to them).\n\n" +
        `${changes.statements.join("\n\n")}\n`,
    );
    writeFileSync(SNAPSHOT_FILE, snapshotText(models));
    console.log(`Wrote ${file.slice(ROOT.length + 1)}`);
  } else {
    console.log("No schema changes.");
  }
  if (!schemaCurrent) {
    mkdirSync(join(ROOT, "generated"), { recursive: true });
    writeFileSync(SCHEMA_FILE, schema);
    console.log("Wrote generated/schema.graphql");
  }
  return 0;
};

if (require.main === module) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (error) {
    if (error instanceof ModelError) {
      console.error(error.message);
      process.exitCode = 1;
    } else {
      throw error;
    }
  }
}
