import { readdirSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { parse } from "yaml";
import {
  FIELD_TYPES,
  FieldDef,
  FieldType,
  FILTER_OPS,
  FilterOp,
  IndexDef,
  ModelDef,
  ON_DELETE,
  OnDelete,
  OrderDef,
  QUERY_VALUE_TYPES,
  QueryDef,
  QueryValueDef,
  QueryValueType,
  RelationDef,
  SYSTEM_FIELD_NAMES,
} from "./types";

/** models/ at the repository root (also /app/models in the image). */
export const MODELS_DIR = resolve(__dirname, "..", "..", "models");

const MODEL_NAME = /^[A-Z][A-Za-z0-9]*$/;
const FIELD_NAME = /^[a-z][A-Za-z0-9]*$/;
const TABLE_NAME = /^[a-z][a-z0-9_]*$/;
const ENUM_VALUE = /^[A-Za-z_][A-Za-z0-9_]*$/;
const DATE = /^\d{4}-\d{2}-\d{2}$/;
const DECIMAL = /^-?\d+(\.\d+)?$/;
const MAX_IDENTIFIER = 63; // PostgreSQL identifiers
/** Tables in schema "app" that are not models. */
const RESERVED_TABLES = ["write_journal"];

const DEFAULT_LIMIT = 50;
const MAX_LIMIT = 100;
const DEFAULT_BULK_MAX_ROWS = 1000;
const DEFAULT_QUERY_TIMEOUT_MS = 5000;
const MAX_QUERY_TIMEOUT_MS = 60000;
/** :name placeholders, not the second colon of a :: cast. */
export const QUERY_PARAM = /(?<!:):([A-Za-z_][A-Za-z0-9_]*)/g;

const COMPARABLE: FieldType[] = ["string", "int", "float", "decimal", "datetime", "date"];
/** Types each filter operator applies to. */
const OP_TYPES: Record<FilterOp, readonly FieldType[]> = {
  eq: FIELD_TYPES.filter((t) => t !== "json"),
  ne: FIELD_TYPES.filter((t) => t !== "json"),
  in: ["string", "int", "float", "decimal", "date", "uuid", "enum"],
  lt: COMPARABLE,
  lte: COMPARABLE,
  gt: COMPARABLE,
  gte: COMPARABLE,
  like: ["string"],
  ilike: ["string"],
  isNull: FIELD_TYPES,
};

/** camelCase to snake_case. */
export const snakeCase = (name: string): string =>
  name.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);

/** Item -> items, Category -> categories, Box -> boxes. */
export const pluralize = (name: string): string => {
  const lower = name[0].toLowerCase() + name.slice(1);
  if (/[^aeiou]y$/.test(lower)) {
    return `${lower.slice(0, -1)}ies`;
  }
  if (/(s|x|z|ch|sh)$/.test(lower)) {
    return `${lower}es`;
  }
  return `${lower}s`;
};

const systemFields = (): { first: FieldDef[]; last: FieldDef[] } => {
  const field = (name: string, type: FieldType, description: string): FieldDef => ({
    name,
    column: snakeCase(name),
    type,
    required: true,
    unique: false,
    description,
    system: true,
  });
  return {
    first: [field("id", "uuid", "Generated by the database.")],
    last: [
      field("ownerCloud", "string", "Cloud whose API created the row."),
      field("version", "int", "Incremented on every update. Pass it back to update / delete."),
      field("createdAt", "datetime", "Creation time (ISO 8601)."),
      field("updatedAt", "datetime", "Time of the last update (ISO 8601)."),
    ],
  };
};

/** Validation error with the file and the path inside it. */
export class ModelError extends Error {}

type Obj = Record<string, unknown>;

class Checker {
  constructor(private readonly source: string) {}

  fail(path: string, message: string): never {
    throw new ModelError(`${this.source}: ${path ? `${path}: ` : ""}${message}`);
  }

  object(value: unknown, path: string, keys: readonly string[]): Obj {
    if (typeof value !== "object" || value === null || Array.isArray(value)) {
      this.fail(path, "must be a mapping");
    }
    for (const key of Object.keys(value)) {
      if (!keys.includes(key)) {
        this.fail(path, `unknown key "${key}" (allowed: ${keys.join(", ")})`);
      }
    }
    return value as Obj;
  }

  string(value: unknown, path: string, pattern?: RegExp): string {
    if (typeof value !== "string" || value === "") {
      this.fail(path, "must be a non-empty string");
    }
    if (pattern && !pattern.test(value)) {
      this.fail(path, `"${value}" does not match ${pattern}`);
    }
    return value;
  }

  optionalString(value: unknown, path: string, pattern?: RegExp): string | undefined {
    return value === undefined ? undefined : this.string(value, path, pattern);
  }

  boolean(value: unknown, path: string, fallback: boolean): boolean {
    if (value === undefined) {
      return fallback;
    }
    if (typeof value !== "boolean") {
      this.fail(path, "must be true or false");
    }
    return value;
  }

  number(value: unknown, path: string, integer: boolean): number {
    if (typeof value !== "number" || !Number.isFinite(value) || (integer && !Number.isInteger(value))) {
      this.fail(path, integer ? "must be an integer" : "must be a number");
    }
    return value;
  }

  list(value: unknown, path: string): unknown[] {
    if (!Array.isArray(value)) {
      this.fail(path, "must be a list");
    }
    return value;
  }
}

const parseDefault = (
  c: Checker,
  value: unknown,
  field: Omit<FieldDef, "default">,
  path: string,
): FieldDef["default"] => {
  if (value === undefined) {
    return undefined;
  }
  switch (field.type) {
    case "string":
      if (typeof value !== "string") c.fail(path, "must be a string");
      return value;
    case "int":
      return c.number(value, path, true);
    case "float":
      return c.number(value, path, false);
    case "decimal":
      if (typeof value === "number") return value;
      return c.string(value, path, DECIMAL);
    case "boolean":
      return c.boolean(value, path, false);
    case "datetime":
      if (value !== "now") c.fail(path, 'only "now" is supported');
      return value;
    case "date":
      return c.string(value, path, DATE);
    case "enum":
      if (typeof value !== "string" || !field.values?.includes(value)) {
        c.fail(path, `must be one of: ${field.values?.join(", ")}`);
      }
      return value;
    default:
      return c.fail(path, `defaults are not supported for type ${field.type}`);
  }
};

const parseField = (c: Checker, name: string, raw: unknown, path: string): FieldDef => {
  if (!FIELD_NAME.test(name)) {
    c.fail(path, `field names must match ${FIELD_NAME}`);
  }
  if ((SYSTEM_FIELD_NAMES as readonly string[]).includes(name)) {
    c.fail(path, `"${name}" is added to every model; do not define it`);
  }
  const f = c.object(raw, path, [
    "type",
    "required",
    "default",
    "unique",
    "maxLength",
    "min",
    "max",
    "values",
    "description",
  ]);
  const type = c.string(f.type, `${path}.type`) as FieldType;
  if (!FIELD_TYPES.includes(type)) {
    c.fail(`${path}.type`, `must be one of: ${FIELD_TYPES.join(", ")}`);
  }
  const column = snakeCase(name);
  if (column.length > MAX_IDENTIFIER) {
    c.fail(path, "name is too long");
  }
  const only = (key: string, types: FieldType[]): void => {
    if (f[key] !== undefined && !types.includes(type)) {
      c.fail(`${path}.${key}`, `only for type ${types.join(" / ")}`);
    }
  };
  only("maxLength", ["string"]);
  only("min", ["int", "float", "decimal"]);
  only("max", ["int", "float", "decimal"]);
  only("values", ["enum"]);

  let values: string[] | undefined;
  if (type === "enum") {
    const list = c.list(f.values, `${path}.values`);
    if (list.length === 0) {
      c.fail(`${path}.values`, "must not be empty");
    }
    values = list.map((v, i) => c.string(v, `${path}.values[${i}]`, ENUM_VALUE));
    if (new Set(values).size !== values.length) {
      c.fail(`${path}.values`, "must not repeat a value");
    }
  }
  const integer = type === "int";
  const field: Omit<FieldDef, "default"> = {
    name,
    column,
    type,
    required: c.boolean(f.required, `${path}.required`, false),
    unique: c.boolean(f.unique, `${path}.unique`, false),
    maxLength:
      f.maxLength === undefined ? undefined : c.number(f.maxLength, `${path}.maxLength`, true),
    min: f.min === undefined ? undefined : c.number(f.min, `${path}.min`, integer),
    max: f.max === undefined ? undefined : c.number(f.max, `${path}.max`, integer),
    values,
    description: c.optionalString(f.description, `${path}.description`),
    system: false,
  };
  if (field.maxLength !== undefined && field.maxLength < 1) {
    c.fail(`${path}.maxLength`, "must be at least 1");
  }
  if (field.min !== undefined && field.max !== undefined && field.min > field.max) {
    c.fail(path, "min must not exceed max");
  }
  if (field.unique && type === "json") {
    c.fail(`${path}.unique`, "not supported for type json");
  }
  const def = parseDefault(c, f.default, field, `${path}.default`);
  return def === undefined ? field : { ...field, default: def };
};

const parseOrder = (c: Checker, raw: unknown, path: string, fields: Map<string, FieldDef>): OrderDef => {
  const o = c.object(raw, path, ["field", "direction"]);
  const field = c.string(o.field, `${path}.field`);
  if (!fields.has(field)) c.fail(`${path}.field`, `unknown field "${field}"`);
  if (fields.get(field)?.type === "json") c.fail(`${path}.field`, "json fields cannot be sorted");
  const direction = o.direction === undefined ? "asc" : c.string(o.direction, `${path}.direction`);
  if (direction !== "asc" && direction !== "desc") {
    c.fail(`${path}.direction`, "must be asc or desc");
  }
  return { field, direction };
};

/** Validates one model file and applies the defaults. */
export const parseModel = (raw: unknown, source: string): ModelDef => {
  const c = new Checker(source);
  const m = c.object(raw, "", [
    "name",
    "plural",
    "table",
    "description",
    "fields",
    "indexes",
    "relations",
    "bulkWrite",
    "queries",
    "list",
  ]);
  const name = c.string(m.name, "name", MODEL_NAME);
  const plural = c.optionalString(m.plural, "plural", FIELD_NAME) ?? pluralize(name);
  const table = c.optionalString(m.table, "table", TABLE_NAME) ?? snakeCase(plural);
  if (table.length > MAX_IDENTIFIER) c.fail("table", "is too long");
  if (RESERVED_TABLES.includes(table)) c.fail("table", `"${table}" is reserved`);

  const rawFields = c.object(m.fields, "fields", Object.keys((m.fields ?? {}) as Obj));
  if (Object.keys(rawFields).length === 0) c.fail("fields", "define at least one field");
  const own = Object.entries(rawFields).map(([n, f]) => parseField(c, n, f, `fields.${n}`));
  const relations = parseRelations(c, m.relations, own);
  const foreignKeys = relations.flatMap((r) => (r.kind === "belongsTo" ? [r.foreignKeyField] : []));
  const system = systemFields();
  const fields = [...system.first, ...own, ...foreignKeys, ...system.last];
  const byName = new Map(fields.map((f) => [f.name, f]));

  const indexes: IndexDef[] = (m.indexes === undefined ? [] : c.list(m.indexes, "indexes")).map(
    (rawIndex, i) => {
      const path = `indexes[${i}]`;
      const ix = c.object(rawIndex, path, ["fields", "unique", "name"]);
      const names = c.list(ix.fields, `${path}.fields`).map((f, j) => {
        const n = c.string(f, `${path}.fields[${j}]`);
        if (!byName.has(n)) c.fail(`${path}.fields[${j}]`, `unknown field "${n}"`);
        return n;
      });
      if (names.length === 0) c.fail(`${path}.fields`, "must not be empty");
      const unique = c.boolean(ix.unique, `${path}.unique`, false);
      const indexName =
        c.optionalString(ix.name, `${path}.name`, TABLE_NAME) ??
        `${table}_${names.map((n) => byName.get(n)?.column).join("_")}_${unique ? "key" : "idx"}`;
      if (indexName.length > MAX_IDENTIFIER) c.fail(`${path}.name`, "is too long; set a shorter name");
      return { name: indexName, fields: names, unique };
    },
  );
  // Every foreign key gets an index (joins and ON DELETE checks), unless an
  // index already starts with it.
  for (const fk of foreignKeys) {
    if (!indexes.some((i) => i.fields[0] === fk.name)) {
      indexes.push({ name: `${table}_${fk.column}_idx`, fields: [fk.name], unique: false });
    }
  }
  if (new Set(indexes.map((i) => i.name)).size !== indexes.length) {
    c.fail("indexes", "index names must be unique");
  }

  const l = c.object(m.list ?? {}, "list", [
    "defaultLimit",
    "maxLimit",
    "filterable",
    "sortable",
    "defaultOrder",
  ]);
  const maxLimit = l.maxLimit === undefined ? MAX_LIMIT : c.number(l.maxLimit, "list.maxLimit", true);
  const defaultLimit =
    l.defaultLimit === undefined
      ? Math.min(DEFAULT_LIMIT, maxLimit)
      : c.number(l.defaultLimit, "list.defaultLimit", true);
  if (defaultLimit < 1 || defaultLimit > maxLimit) {
    c.fail("list.defaultLimit", "must be between 1 and list.maxLimit");
  }

  const filterable: Record<string, FilterOp[]> = {};
  const rawFilterable = c.object(l.filterable ?? {}, "list.filterable", Object.keys((l.filterable ?? {}) as Obj));
  for (const [fieldName, rawOps] of Object.entries(rawFilterable)) {
    const path = `list.filterable.${fieldName}`;
    const field = byName.get(fieldName) ?? c.fail(path, `unknown field "${fieldName}"`);
    const ops = c.list(rawOps, path).map((op, i) => {
      const o = c.string(op, `${path}[${i}]`) as FilterOp;
      if (!FILTER_OPS.includes(o)) c.fail(`${path}[${i}]`, `must be one of: ${FILTER_OPS.join(", ")}`);
      if (!OP_TYPES[o].includes(field.type)) c.fail(`${path}[${i}]`, `"${o}" does not apply to type ${field.type}`);
      if (o === "isNull" && field.required) c.fail(`${path}[${i}]`, "isNull needs a field that is not required");
      return o;
    });
    if (ops.length === 0) c.fail(path, "must not be empty");
    filterable[fieldName] = [...new Set(ops)];
  }

  const sortable = (l.sortable === undefined ? [] : c.list(l.sortable, "list.sortable")).map((f, i) => {
    const n = c.string(f, `list.sortable[${i}]`);
    const field = byName.get(n) ?? c.fail(`list.sortable[${i}]`, `unknown field "${n}"`);
    if (field.type === "json") c.fail(`list.sortable[${i}]`, "json fields cannot be sorted");
    return n;
  });

  const defaultOrder =
    l.defaultOrder === undefined
      ? [{ field: "createdAt", direction: "asc" as const }]
      : c.list(l.defaultOrder, "list.defaultOrder").map((o, i) => parseOrder(c, o, `list.defaultOrder[${i}]`, byName));

  const b = c.object(m.bulkWrite ?? {}, "bulkWrite", ["update", "delete", "maxRows"]);
  const bulkWrite = {
    update: c.boolean(b.update, "bulkWrite.update", false),
    delete: c.boolean(b.delete, "bulkWrite.delete", false),
    maxRows: b.maxRows === undefined ? DEFAULT_BULK_MAX_ROWS : c.number(b.maxRows, "bulkWrite.maxRows", true),
  };
  if (bulkWrite.maxRows < 1) c.fail("bulkWrite.maxRows", "must be at least 1");
  if ((bulkWrite.update || bulkWrite.delete) && Object.keys(filterable).length === 0) {
    c.fail("bulkWrite", "needs list.filterable: the conditions of a bulk write use the same fields");
  }

  const rawQueries = c.object(m.queries ?? {}, "queries", Object.keys((m.queries ?? {}) as Obj));
  const queries = Object.entries(rawQueries).map(([n, q]) => parseQuery(c, n, q, `queries.${n}`));

  return {
    name,
    plural,
    table,
    description: c.optionalString(m.description, "description"),
    fields,
    indexes,
    relations: relations.map((r) => r.def),
    bulkWrite,
    queries,
    list: { defaultLimit, maxLimit, filterable, sortable: [...new Set(sortable)], defaultOrder },
    source,
  };
};

const parseRelations = (
  c: Checker,
  raw: unknown,
  own: FieldDef[],
): ({ kind: "belongsTo"; def: RelationDef; foreignKeyField: FieldDef } | { kind: "hasMany"; def: RelationDef })[] => {
  const rels = c.object(raw ?? {}, "relations", Object.keys((raw ?? {}) as Obj));
  const taken = new Set<string>([...SYSTEM_FIELD_NAMES, ...own.map((f) => f.name)]);
  return Object.entries(rels).map(([name, value]) => {
    const path = `relations.${name}`;
    if (!FIELD_NAME.test(name)) c.fail(path, `relation names must match ${FIELD_NAME}`);
    if (taken.has(name)) c.fail(path, `"${name}" is already a field`);
    taken.add(name);
    const r = c.object(value, path, ["belongsTo", "hasMany", "required", "onDelete", "foreignKey", "description"]);
    if ((r.belongsTo === undefined) === (r.hasMany === undefined)) {
      c.fail(path, "set exactly one of belongsTo and hasMany");
    }
    if (r.hasMany !== undefined) {
      for (const key of ["required", "onDelete"]) {
        if (r[key] !== undefined) c.fail(`${path}.${key}`, "only for belongsTo");
      }
      return {
        kind: "hasMany" as const,
        def: {
          kind: "hasMany",
          name,
          target: c.string(r.hasMany, `${path}.hasMany`, MODEL_NAME),
          foreignKey: c.string(r.foreignKey, `${path}.foreignKey`, FIELD_NAME),
        },
      };
    }
    if (r.foreignKey !== undefined) c.fail(`${path}.foreignKey`, "only for hasMany");
    const target = c.string(r.belongsTo, `${path}.belongsTo`, MODEL_NAME);
    const required = c.boolean(r.required, `${path}.required`, false);
    const onDelete = (r.onDelete === undefined ? "restrict" : c.string(r.onDelete, `${path}.onDelete`)) as OnDelete;
    if (!ON_DELETE.includes(onDelete)) c.fail(`${path}.onDelete`, `must be one of: ${ON_DELETE.join(", ")}`);
    if (onDelete === "setNull" && required) c.fail(`${path}.onDelete`, "setNull needs a relation that is not required");
    const fieldName = `${name}Id`;
    if (taken.has(fieldName)) c.fail(path, `the foreign key field "${fieldName}" is already a field`);
    taken.add(fieldName);
    const foreignKeyField: FieldDef = {
      name: fieldName,
      column: snakeCase(fieldName),
      type: "uuid",
      required,
      unique: false,
      description: c.optionalString(r.description, `${path}.description`) ?? `ID of the ${target} (relation ${name}).`,
      system: false,
      references: { model: target, table: "", onDelete },
    };
    return {
      kind: "belongsTo" as const,
      def: { kind: "belongsTo", name, target, field: fieldName },
      foreignKeyField,
    };
  });
};

const parseQueryValues = (c: Checker, raw: unknown, path: string, required: boolean): QueryValueDef[] => {
  const values = c.object(raw ?? {}, path, Object.keys((raw ?? {}) as Obj));
  return Object.entries(values).map(([name, value]) => {
    const p = `${path}.${name}`;
    if (!FIELD_NAME.test(name)) c.fail(p, `names must match ${FIELD_NAME}`);
    const v = c.object(value, p, ["type", "required", "description"]);
    const type = c.string(v.type, `${p}.type`) as QueryValueType;
    if (!QUERY_VALUE_TYPES.includes(type)) c.fail(`${p}.type`, `must be one of: ${QUERY_VALUE_TYPES.join(", ")}`);
    return {
      name,
      type,
      required: c.boolean(v.required, `${p}.required`, required),
      description: c.optionalString(v.description, `${p}.description`),
    };
  });
};

const parseQuery = (c: Checker, name: string, raw: unknown, path: string): QueryDef => {
  if (!FIELD_NAME.test(name)) c.fail(path, `query names must match ${FIELD_NAME}`);
  const q = c.object(raw, path, ["description", "sql", "params", "returns", "list", "timeoutMs"]);
  const sql = c.string(q.sql, `${path}.sql`).trim();
  const params = parseQueryValues(c, q.params, `${path}.params`, false);
  const returns = parseQueryValues(c, q.returns, `${path}.returns`, false);
  if (returns.length === 0) c.fail(`${path}.returns`, "define at least one column");
  const used = new Set([...sql.matchAll(QUERY_PARAM)].map((match) => match[1]));
  for (const p of used) {
    if (!params.some((d) => d.name === p)) c.fail(`${path}.sql`, `:${p} is not declared in params`);
  }
  for (const p of params) {
    if (!used.has(p.name)) c.fail(`${path}.params.${p.name}`, "is not used in sql");
  }
  const timeoutMs =
    q.timeoutMs === undefined ? DEFAULT_QUERY_TIMEOUT_MS : c.number(q.timeoutMs, `${path}.timeoutMs`, true);
  if (timeoutMs < 1 || timeoutMs > MAX_QUERY_TIMEOUT_MS) {
    c.fail(`${path}.timeoutMs`, `must be between 1 and ${MAX_QUERY_TIMEOUT_MS}`);
  }
  return {
    name,
    description: c.optionalString(q.description, `${path}.description`),
    sql,
    params,
    returns,
    list: c.boolean(q.list, `${path}.list`, true),
    timeoutMs,
  };
};

/**
 * Checks what depends on other models (relation targets) and fills in the
 * referenced tables. Called by loadModels; call it after parseModel when
 * models are built in code (tests).
 */
export const resolveModels = (models: ModelDef[]): ModelDef[] => {
  const byName = new Map(models.map((m) => [m.name, m]));
  for (const m of models) {
    const fail = (path: string, message: string): never => {
      throw new ModelError(`${m.source}: ${path}: ${message}`);
    };
    for (const r of m.relations) {
      const target = byName.get(r.target) ?? fail(`relations.${r.name}`, `unknown model "${r.target}"`);
      if (r.kind === "belongsTo") {
        const fk = m.fields.find((f) => f.name === r.field);
        if (fk?.references) fk.references.table = target.table;
      } else {
        const inverse = target.relations.find((t) => t.name === r.foreignKey);
        if (!inverse || inverse.kind !== "belongsTo" || inverse.target !== m.name) {
          fail(
            `relations.${r.name}.foreignKey`,
            `${r.target} has no belongsTo relation "${r.foreignKey}" to ${m.name}`,
          );
        }
      }
    }
  }
  return models;
};

/** Reads and validates every models/*.yaml (sorted by file name). */
export const loadModels = (dir: string = MODELS_DIR): ModelDef[] => {
  const files = readdirSync(dir)
    .filter((f) => f.endsWith(".yaml") || f.endsWith(".yml"))
    .sort();
  const models = files.map((file) => {
    const source = `models/${file}`;
    let raw: unknown;
    try {
      raw = parse(readFileSync(join(dir, file), "utf8"));
    } catch (error) {
      throw new ModelError(`${source}: invalid YAML: ${(error as Error).message}`);
    }
    return parseModel(raw, source);
  });
  for (const key of ["name", "plural", "table"] as const) {
    const seen = new Map<string, string>();
    for (const model of models) {
      const other = seen.get(model[key]);
      if (other) {
        throw new ModelError(`${model.source}: ${key} "${model[key]}" is also used by ${other}`);
      }
      seen.set(model[key], model.source);
    }
  }
  return resolveModels(models);
};
